"""Export every Blender asset of the outpost as FBX parts for Unreal Engine.
Each mesh object becomes <asset>__<object>.fbx with its pivot at the object origin, and
OutpostParts.inl lists where each part sits inside its asset (already in Unreal space: cm, Y mirrored)."""
import os, sys, bpy, math
from mathutils import Matrix
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import make_assets as M
OUT = sys.argv[sys.argv.index('--out')+1] if '--out' in sys.argv else os.path.join(HERE, 'fbx')
INL = sys.argv[sys.argv.index('--inl')+1] if '--inl' in sys.argv else os.path.join(OUT, 'OutpostParts.inl')
os.makedirs(OUT, exist_ok=True)
rows = []
def export_fbx(name):
    objs = [o for o in bpy.context.scene.objects if o.type == 'MESH']
    for o in objs:
        bpy.ops.object.select_all(action='DESELECT'); o.select_set(True); bpy.context.view_layer.objects.active = o
        for md in list(o.modifiers):
            try: bpy.ops.object.modifier_apply(modifier=md.name)
            except Exception: pass
    for o in objs:
        mw = o.matrix_world.copy(); loc, rot, sc = mw.decompose()
        part = f'{name}__{o.name}'.replace('.', '_')
        o.parent = None; o.matrix_world = Matrix.Identity(4)
        o.name = part; o.data.name = part
        bpy.ops.object.select_all(action='DESELECT'); o.select_set(True); bpy.context.view_layer.objects.active = o
        bpy.ops.export_scene.fbx(filepath=os.path.join(OUT, part + '.fbx'), use_selection=True, object_types={'MESH'},
                                 apply_unit_scale=True, apply_scale_options='FBX_SCALE_ALL', bake_space_transform=False,
                                 mesh_smooth_type='FACE', use_mesh_modifiers=True, add_leaf_bones=False, path_mode='STRIP')
        # Unreal space: centimetres, Y mirrored (right-handed Blender -> left-handed Unreal)
        rows.append((name, part, loc.x*100, -loc.y*100, loc.z*100, -rot.x, rot.y, -rot.z, rot.w, sc.x, sc.y, sc.z))
    print('fbx', name, len(objs))
M.export = export_fbx
def build_sign():
    # 1 x 1 m quad facing Blender -Y (Unreal +Y) with the image the right way up
    M.reset(); import bmesh
    me = bpy.data.meshes.new('sign'); o = bpy.data.objects.new('sign', me); bpy.context.scene.collection.objects.link(o)
    bm = bmesh.new(); vs = [bm.verts.new(p) for p in ((-0.5,0,-0.5),(0.5,0,-0.5),(0.5,0,0.5),(-0.5,0,0.5))]
    f = bm.faces.new(vs); uv = bm.loops.layers.uv.new('UVMap')
    for loop, t in zip(f.loops, ((0,0),(1,0),(1,1),(0,1))): loop[uv].uv = t
    bm.to_mesh(me); bm.free(); M.setmat(o, M.mat('sign', M.C(255,255,255), 0.0, 0.5)); export_fbx('sign')
def build_rock():
    import random; random.seed(6)
    M.reset(); bpy.ops.mesh.primitive_ico_sphere_add(subdivisions=2, radius=1.0); o = bpy.context.active_object; o.name = 'rock'
    for v in o.data.vertices:
        k = 0.8 + 0.35*random.random(); v.co.x *= k; v.co.y *= k; v.co.z *= k*0.7
    M.setmat(o, M.mat('rock', M.C(109,111,116), 0.0, 0.95)); export_fbx('rock')
for f in [M.build_hab, M.build_corridors, M.build_lab, M.build_greenhouse, M.build_plants, M.build_solar, M.build_battery,
          M.build_reactor, M.build_dish, M.build_rover, M.build_lander, M.build_small, M.build_people, build_rock, build_sign]:
    f()
with open(INL, 'w') as fh:
    fh.write('// Generated by blender/export_fbx.py. Asset, mesh, location (cm), rotation quat (x,y,z,w), scale.\n')
    for r in rows:
        fh.write('{TEXT("%s"), TEXT("%s"), FVector(%.2ff, %.2ff, %.2ff), FQuat(%.6ff, %.6ff, %.6ff, %.6ff), FVector(%.4ff, %.4ff, %.4ff)},\n' % r)
print('parts', len(rows))
